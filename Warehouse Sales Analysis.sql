-- Ranking Analysis (Rank dimension by measure)

-- Which 5 products generate the highest revenue?
SELECT TOP 5 
	prod.product_name, 
	SUM(sal.sales_amount) AS total_revenue
FROM fact_sales sal
LEFT JOIN dim_products prod
	ON sal.product_key = prod.product_key
GROUP BY prod.product_name
ORDER BY total_revenue DESC;

-- What are the 5 worst-performing products in terms of sales?
SELECT TOP 5 
	prod.product_name, 
	SUM(sal.sales_amount) AS total_revenue
FROM fact_sales sal
LEFT JOIN dim_products prod
	ON sal.product_key = prod.product_key
GROUP BY prod.product_name
ORDER BY total_revenue;

-- Find the top 10 customers who have generated the highest revenue
WITH ranking_CTE AS (
	SELECT 
		CONCAT_WS(' ', cust.first_name, cust.last_name) AS customer_name,
		SUM(sal.sales_amount) AS total_revenue,
		ROW_NUMBER() OVER(ORDER BY SUM(sal.sales_amount) DESC) AS row_rank
	FROM fact_sales sal
	LEFT JOIN dim_customers cust
		ON sal.customer_key = cust.customer_key
	GROUP BY CONCAT_WS(' ', cust.first_name, cust.last_name)
)
SELECT * FROM ranking_CTE WHERE row_rank <= 5 ORDER BY row_rank;

-- Find the 3 customers with the fewest orders placed
SELECT * FROM (
	SELECT 
		CONCAT_WS(' ', cust.first_name, cust.last_name) AS customer_name,
		COUNT(Distinct order_number) AS num_orders,
		ROW_NUMBER() OVER (ORDER BY COUNT(Distinct order_number)) AS row_rank
	FROM fact_sales sal
	LEFT JOIN dim_customers cust
		ON sal.customer_key = cust.customer_key
	GROUP BY CONCAT_WS(' ', cust.first_name, cust.last_name)
) AS ranking_subq
WHERE row_rank <= 3
ORDER BY row_rank;



